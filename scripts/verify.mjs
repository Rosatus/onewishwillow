import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const artifacts = fileURLToPath(new URL('../artifacts/', import.meta.url))
await mkdir(artifacts, { recursive: true })
const server = await createServer({ server: { host: '127.0.0.1', port: 7100, strictPort: true } })
await server.listen()
const browser = await chromium.launch({
  headless: true,
  args: ['--enable-webgl', '--ignore-gpu-blocklist', '--use-angle=swiftshader'],
})
const errors = []
const report = { checks: [], errors }

try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
  const page = await context.newPage()
  page.on('response', response => { if (response.status() >= 400 && response.url().includes('127.0.0.1')) errors.push(`HTTP ${response.status()}: ${response.url()}`) })
  page.on('pageerror', (error) => errors.push(`page: ${error.message}`))
  page.on('console', (message) => {
    if (message.type() === 'error' && !message.text().includes('net::ERR')) errors.push(`console: ${message.text()}`)
  })
  await page.goto('http://127.0.0.1:7100/', { waitUntil: 'domcontentloaded' })
  await page.locator('.app.is-ready').waitFor({ timeout: 30000 })
  await page.waitForTimeout(2200)
  const scene = await page.evaluate(() => ({
    canvas: document.querySelectorAll('canvas').length,
    width: document.querySelector('canvas')?.width,
    height: document.querySelector('canvas')?.height,
    title: document.querySelector('h1')?.textContent,
  }))
  if (!scene.canvas || !scene.width) throw new Error('3D canvas did not render')
  report.checks.push({ name: 'desktop scene', ...scene })
  await page.screenshot({ path: `${artifacts}desktop-home.png` })

  await page.getByRole('button', { name: '打开柳盒' }).click()
  await page.waitForTimeout(1350)
  await page.screenshot({ path: `${artifacts}desktop-opening-lid.png` })
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${artifacts}desktop-opening-branch.png` })
  await page.locator('.stage-ritual').waitFor()
  await page.waitForTimeout(1300)
  await page.screenshot({ path: `${artifacts}desktop-ritual.png` })
  await page.getByRole('button', { name: '按住折枝，许下愿望' }).click()
  await page.getByRole('alert').filter({ hasText: '至少四个字' }).waitFor()
  await page.locator('#wish').fill('我希望我所爱之人也爱着我，永远只爱我一个人。')
  const branch = page.getByRole('button', { name: '按住折枝，许下愿望' })
  const box = await branch.boundingBox()
  if (!box) throw new Error('Branch control has no bounding box')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.waitForTimeout(450)
  await page.mouse.up()
  assert.equal(await branch.getAttribute('class'), 'branch-ritual  ')
  assert.equal(await page.locator('.stage-ritual').count(), 1)
  report.checks.push({ name: 'release cancels hold', result: 'passed' })
  await page.mouse.down()
  await page.waitForTimeout(1900)
  await page.mouse.up()
  await page.locator('.answer.is-visible').waitFor({ timeout: 12000 })
  await page.getByText('愿望实现了。', { exact: true }).waitFor()
  report.checks.push({ name: 'wish ritual', result: 'passed', archived: await page.locator('.nav-button b').textContent() })
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${artifacts}desktop-answer.png` })
  await page.locator('.answer__scroll').evaluate((element) => { element.scrollTop = element.scrollHeight })
  await page.waitForTimeout(350)
  await page.screenshot({ path: `${artifacts}desktop-price.png` })
  await page.getByRole('button', { name: '回到首页' }).click()
  await page.getByRole('button', { name: /树洞/ }).click()
  await page.locator('.archive-drawer.is-open .archive-item').waitFor()
  report.checks.push({ name: 'local archive', result: 'passed' })
  await page.getByRole('button', { name: '关闭树洞' }).click()
  await page.getByRole('button', { name: '许愿须知' }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('button', { name: '我已读完' }).click()
  await page.reload()
  await page.locator('.app.is-ready').waitFor()
  assert.equal(await page.locator('.nav-button b').textContent(), '01')
  await page.getByRole('button', { name: '打开柳盒' }).click()
  await page.getByRole('button', { name: '返回一愿柳首页' }).click()
  await page.waitForTimeout(3000)
  assert.equal(await page.locator('.stage-hero').count(), 1)
  report.checks.push({ name: 'archive persists and exiting cancels opening', result: 'passed' })
  report.checks.push({ name: 'rules dialog', result: 'passed' })
  await context.close()

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true })
  const phone = await mobile.newPage()
  phone.on('pageerror', (error) => errors.push(`mobile page: ${error.message}`))
  await phone.goto('http://127.0.0.1:7100/', { waitUntil: 'domcontentloaded' })
  await phone.locator('.app.is-ready').waitFor({ timeout: 30000 })
  await phone.waitForTimeout(1700)
  await phone.screenshot({ path: `${artifacts}mobile-home.png` })
  const overflow = await phone.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  if (overflow) throw new Error('Mobile page has horizontal overflow')
  await phone.getByRole('button', { name: '打开柳盒' }).click()
  await phone.waitForTimeout(1500)
  await phone.screenshot({ path: `${artifacts}mobile-opening.png` })
  await phone.locator('.stage-ritual').waitFor()
  await phone.waitForTimeout(1000)
  await phone.screenshot({ path: `${artifacts}mobile-ritual.png` })
  const textareaVisible = await phone.locator('#wish').isVisible()
  const branchVisible = await phone.getByRole('button', { name: '按住折枝，许下愿望' }).isVisible()
  if (!textareaVisible || !branchVisible) throw new Error('Mobile ritual controls are not visible')
  report.checks.push({ name: 'mobile layout', result: 'passed', horizontalOverflow: overflow })
  const mobileBranch = phone.getByRole('button', { name: '按住折枝，许下愿望' })
  const photo = await phone.locator('.branch-photo__intact--left').evaluate(image => ({ loaded: image.complete && image.naturalWidth > 0, width: image.getBoundingClientRect().width }))
  assert.ok(photo.loaded && photo.width > 250)
  await phone.locator('#wish').fill('希望有花不完的钱')
  const touch = await phone.context().newCDPSession(phone)
  const target = await mobileBranch.boundingBox()
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: target.x + target.width / 2, y: target.y + target.height / 2 }] })
  await phone.waitForTimeout(1900)
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await phone.locator('.answer.is-visible').waitFor({ timeout: 12000 })
  report.checks.push({ name: 'mobile touch wish', result: 'passed', branchImage: photo })
  await mobile.close()

  const reduced = await browser.newContext({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce' })
  const keyboard = await reduced.newPage()
  await keyboard.goto('http://127.0.0.1:7100/')
  await keyboard.locator('.app.is-ready').waitFor()
  await keyboard.getByRole('button', { name: '打开柳盒' }).click()
  await keyboard.locator('#wish').fill('希望有花不完的钱')
  const keyboardBranch = keyboard.getByRole('button', { name: '按住折枝，许下愿望' })
  await keyboardBranch.focus()
  await keyboard.keyboard.down('Space')
  await keyboard.waitForTimeout(1900)
  await keyboard.keyboard.up('Space')
  await keyboard.locator('.answer.is-visible').waitFor()
  await keyboard.getByRole('button', { name: '重新体验' }).click()
  await keyboard.locator('.stage-ritual').waitFor()
  assert.equal(await keyboard.locator('#wish').inputValue(), '')
  assert.equal(await keyboardBranch.getAttribute('aria-disabled'), 'false')
  report.checks.push({ name: 'keyboard, reduced motion and replay', result: 'passed' })
  await reduced.close()

  if (errors.length) throw new Error(`Browser errors: ${errors.join(' | ')}`)
  await writeFile(`${artifacts}verification.json`, JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally {
  await browser.close()
  await server.close()
}
